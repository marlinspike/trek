"""The contract between a battle and whoever presents it [E].

The battle screen is typed against `Session`, not against `BattleSession`, so mypy fails the build if the UI
reaches for anything not listed here. Anything that honours this protocol can be presented by the same screen:

- `BattleSession` (session/battle.py) plays the battle in this process;
- a networked session would hold a mirror of the world, kept in step by exchanging orders (the simulation is
  deterministic and every order is a `Command`, which `session/wire.py` turns into JSON and back), and say
  the same news as the host;
- a replay would feed a recorded command log through the same clock.

The rules the code is held to (tests/test_architecture.py):

1. Nothing outside `begin.ui` imports pygame or `begin.ui`: the game runs without a screen.
2. `begin.ui` never imports the world, the AI, the language models or the session's machinery; it talks to a
   `Session`, reads an `Observation`, and changes the game only by orders (`submit`, `say`).
3. What the session has to tell the captain comes out as `News` (session/news.py), in tones, never colours.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Callable, Protocol

if TYPE_CHECKING:
    from ..console.orders import TacticalOrder
    from ..console.parser import ParseResult
    from ..crew.characters import OfficerProfile
    from ..crew.counsel import Plan
    from ..crew.situation import MissionView, Situation
    from ..crew.hails import Comms
    from ..crew.officers import Activity
    from ..crew.proposals import Proposal
    from ..help.coach import HelpContext
    from ..sim.commands import Command
    from ..sim.observation import Observation
    from ..sim.ship import Ship
    from ..tour.run import TourRun
    from .command import Recording
    from .debrief import Debrief
    from .news import News
    from .prefs import BridgePrefs


class Session(Protocol):
    """One battle being played, as a presenter sees it."""

    # ---- state shown on screen (the presenter may set `paused`, `speed` and `chart_auto`; it reads the rest)
    player_id: int | None
    paused: bool
    speed: float
    acc: float                       # battle seconds since the last tick, for interpolating between ticks
    obs: Observation
    comms: Comms                     # hail channels, for the comms card
    prefs: BridgePrefs               # how much of the bridge the captain wants
    proposal: Proposal | None        # an officer's proposed order, waiting on Y or N
    condition: str | None            # alert condition
    recording: Recording | None      # a named order being recorded
    style: str | None                # the command style promised
    style_broken: str | None
    chart_auto: bool
    captain_typing: bool             # set by the presenter each frame
    busy_elsewhere: bool             # set by the presenter each frame: a screen is open over the battle

    @property
    def player(self) -> Ship | None: ...
    @property
    def title(self) -> str: ...
    @property
    def tick_length(self) -> float: ...

    # ---- the outbox and the clock
    def subscribe(self, listener: Callable[[News], None]) -> None: ...
    def update(self, dt: float, rate: float | None = None) -> int: ...
    def observe(self) -> Observation: ...
    def close(self) -> None: ...

    # ---- orders
    def submit(self, cmd: Command) -> str | None: ...
    def say(self, text: str) -> None: ...
    def fire_phasers(self, banks: tuple[int, ...] | None) -> None: ...
    def fire_torpedoes(self, tubes: tuple[int, ...] | None) -> None: ...
    def launch_probe(self) -> None: ...
    def toggle_reserve(self, i: int) -> None: ...
    def order_ally(self, ally: int, order: str, target: int | None = None, value: float | None = None) -> None: ...
    def ally_report(self, sid: int) -> None: ...
    def take_command(self, sid: int) -> None: ...
    def hail(self, target: int | None, words: str) -> None: ...
    def open_channel(self, sid: int) -> None: ...
    def accept_proposal(self) -> bool: ...
    def belay_proposal(self) -> bool: ...
    def style_check(self, cmd: Command | None = None, why: str | None = None) -> None: ...

    # ---- questions the screen asks
    def preview(self, text: str) -> ParseResult | None: ...
    def understood(self, line: str) -> str | None: ...
    def display(self, live: str) -> list[str] | None: ...
    def live_chart(self) -> list[str] | None: ...
    def ship_name(self, sid: int) -> str: ...
    def allies(self) -> list[Ship]: ...
    def nearest_base(self, ally: Ship) -> Ship | None: ...
    def inbound(self) -> list[tuple[str, float]]: ...
    def in_battle(self) -> bool: ...
    def officers(self) -> dict[str, OfficerProfile]: ...
    def find_officer(self, who: str) -> OfficerProfile | None: ...
    def in_command(self) -> OfficerProfile | None: ...
    def trust(self, officer: str) -> str: ...
    def officer_activity(self, obs: Observation) -> list[Activity]: ...
    def officer_name(self, oid: str) -> str: ...
    def repair_officer(self, ship: Ship) -> OfficerProfile | None: ...
    def named_orders(self) -> dict[str, TacticalOrder]: ...
    def running_order(self) -> str | None: ...
    def help_context(self) -> HelpContext: ...
    def debrief(self, rows: int = 9) -> Debrief: ...
    def situation(self) -> Situation | None: ...
    def mission(self) -> MissionView | None: ...
    def counsel(self, force: bool = False) -> list[Plan]: ...
    def follow(self, plan: Plan, lines: list[str] | None = None) -> None: ...

    # ---- a tour of duty
    def join_tour(self, run: TourRun) -> None: ...
    def finish_tour(self, run: TourRun) -> None: ...


__all__ = ["Session"]
