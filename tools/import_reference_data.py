#!/usr/bin/env python3
"""Import Begin's ship, ordnance and faction statistics into our TOML content.

Source: the JSON data files of https://github.com/fireflyk64/begin (BSD-2-Clause,
commit 0fdade8), which were extracted from begin2.exe with v1.65 weapon mount
counts. We copy numeric game statistics only (facts about the original game),
not text such as end-of-game verdicts, which we rewrite ourselves.

Usage:
    python tools/import_reference_data.py <path-to>/crates/begin-core/data

The output is `src/begin/content/data/classes.toml` and `ordnance.toml`.
Hull geometry, mounts and everything marked as a remake extension live in
hand-written files next to them and are never overwritten by this tool.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

FACTION_IDS = {
    "Federation": "federation",
    "Klingon": "klingon",
    "Romulan": "romulan",
    "Orion Pirate": "orion",
}

# Classes that the 1.65 manual (Appendix C) documents; the rest arrived with 2.0.
CLASSES_165 = {
    ("federation", "IN"), ("federation", "DE"), ("federation", "HC"), ("federation", "DN"),
    ("klingon", "ES"), ("klingon", "FR"), ("klingon", "DR"),
    ("romulan", "WE"), ("romulan", "FR"), ("romulan", "BP"),
    ("orion", "AS"), ("orion", "RA"), ("orion", "AN"),
}

STAT_FIELDS = [
    "crew", "mass", "max_warp", "w1accel", "decel", "warp_power_use", "w1turn",
    "destruct", "destruct_energy", "scanner_reflect", "scanner_range",
    "reactors", "reactor_output", "batteries", "battery_capacity",
    "banks", "banks_rate", "banks_charge", "banks_range",
    "tubes", "launchers", "drives", "warp_power", "warp_efficiency",
    "shields", "shield_strength", "shield_absorption", "shield_recharge", "shield_energy",
    "transporters", "beam_cap", "beam_range",
    "can_cloak", "cloak_energy", "armour", "mass_capacity", "docked_repair_ratio",
    "life_support", "has_impulse", "has_tractor", "tractor_strength", "tractor_energy",
    "torps_carried", "probes_carried",
]

# Deliberate changes to the imported statistics [E], with the comment written beside each value.
# See docs/DEVIATIONS.md. Everything else is copied unchanged.
OVERRIDES: dict[str, dict[str, tuple[Any, str]]] = {
    "federation.dn": {
        "max_warp": (9.5, ""),
        "warp_power": (305.0, "three drives must supply 9.5 × warp_power_use (95) to reach warp 9.5"),
        "torps_carried": (10000, "the player's flagship: a deep magazine so eight tubes can keep firing"),
        "probes_carried": (250, "the player's flagship: probes to spare"),
    },
    "klingon.dr": {
        "shield_absorption": (0.6, "was 0.8: full Federation volleys couldn't wear its shields down"),
    },
}

REPAIR_FIELDS = {
    "reactor": "reactor_repair", "battery": "battery_repair", "phaser": "banks_repair",
    "tube": "tube_repair", "launcher": "probe_repair", "drive": "drive_repair",
    "shield": "shield_repair", "transporter": "transporter_repair",
    "sensors": "scanner_repair", "cloak": "cloak_repair", "impulse": "impulse_repair",
    "tractor": "tractor_repair",
}


def toml_value(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    raise TypeError(type(v))


def class_id(faction: str, abbrev: str) -> str:
    return f"{faction}.{abbrev.lower()}"


def main(src: Path, out: Path) -> None:
    ships = json.loads((src / "ships.json").read_text())
    torps = json.loads((src / "torps.json").read_text())
    probes = json.loads((src / "probes.json").read_text())

    lines = [
        "# GENERATED by tools/import_reference_data.py — do not edit by hand.",
        "# Begin 2.0 statistics (begin2.exe via fireflyk64/begin), v1.65 mount counts.",
        "",
    ]
    for s in ships:
        faction = FACTION_IDS[s["nation"]]
        cid = class_id(faction, s["abbrev"])
        lines.append("[[class]]")
        lines.append(f"id = {toml_value(cid)}")
        lines.append(f"name = {toml_value(s['name'])}")
        lines.append(f"abbrev = {toml_value(s['abbrev'])}")
        lines.append(f"faction = {toml_value(faction)}")
        era = "1.65" if (faction, s["abbrev"]) in CLASSES_165 else "2.0"
        lines.append(f"era = {toml_value(era)}")
        lines.append(f"torpedo = {toml_value(s['torp'].lower() if s['tubes'] else '')}")
        lines.append(f"probe = {toml_value(s['probe'].lower() if s['launchers'] else '')}")
        for f in STAT_FIELDS:
            value, note = OVERRIDES.get(cid, {}).get(f, (s[f], ""))
            lines.append(f"{f} = {toml_value(value)}" + (f"   # {note}" if note else ""))
        lines.append(f"ship_names = {toml_value(s['ship_names'])}")
        lines.append("[class.repair]")
        for k, f in REPAIR_FIELDS.items():
            lines.append(f"{k} = {toml_value(s[f])}")
        lines.append("")
    (out / "classes.toml").write_text("\n".join(lines))

    olines = [
        "# GENERATED by tools/import_reference_data.py — do not edit by hand.",
        "# Torpedo and probe designs from begin2.exe (via fireflyk64/begin).",
        "",
    ]
    for t in torps:
        olines.append("[[torpedo]]")
        olines.append(f"id = {toml_value(t['name'].lower())}")
        olines.append(f"name = {toml_value(t['desc'])}")
        for f in ("velocity", "damage", "arm_time", "max_time_fuse", "max_prox", "homing",
                  "speed_variance", "warhead_type", "charge_time", "load_energy"):
            olines.append(f"{f} = {toml_value(t[f])}")
        olines.append("")
    for p in probes:
        olines.append("[[probe]]")
        olines.append(f"id = {toml_value(p['name'].lower())}")
        olines.append(f"name = {toml_value(p['desc'])}")
        for f in ("velocity", "damage", "arm_time", "max_time_fuse", "max_prox", "homing",
                  "scan_range"):
            olines.append(f"{f} = {toml_value(p[f])}")
        olines.append("")
    (out / "ordnance.toml").write_text("\n".join(olines))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = Path(__file__).resolve().parent.parent
    main(Path(sys.argv[1]), root / "src" / "begin" / "content" / "data")
